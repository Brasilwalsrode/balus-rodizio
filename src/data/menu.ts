export const MIN_CUSTOM_MEAT_COUNT = 3;
export const CUSTOM_BASE_PRICE_SLUG = "369-grundpreis-menu-selber-gestalten";

export const MEAT_PREFIXES = ["Gf-", "Sc-", "Ri-", "La-", "Br-", "Sp-"] as const;

export function isMeatItem(item: Pick<MenuItem, "name" | "category">): boolean {
  return (
    item.category === "Menü selber gestalten" &&
    MEAT_PREFIXES.some((prefix) => item.name.startsWith(prefix))
  );
}

export function getMeatSubgroup(name: string): string {
  if (name.startsWith("Gf-")) return "Geflügel";
  if (name.startsWith("Sc-")) return "Schwein";
  if (name.startsWith("Ri-")) return "Rind & Kalb";
  if (name.startsWith("La-")) return "Lamm";
  if (name.startsWith("Br-")) return "Bratwurst & Wurst";
  if (name.startsWith("Sp-")) return "Im Speckmantel";
  return "Fleischsorten";
}

